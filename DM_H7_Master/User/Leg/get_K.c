{
    if (rx_data->data[0] != 0xCD || rx_data->data[49] != 0xDC)
    {
        return -1;
    }
    memcpy(ChassisL_LQR_K, rx_data->K_data.LQR_K, sizeof(float) * 12);
    return 0;
}